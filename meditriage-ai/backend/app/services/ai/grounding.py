from __future__ import annotations

from typing import Dict, List, Set, Tuple
from app.services.ai.schemas import CaseAnalysis, DifferentialItem


class GroundingChecker:
    """
    RAG Grounding Verification Engine.
    Ensures that every differential diagnosis generated by the LLM is anchored
    in verified RAG knowledge chunks. Any ungrounded or hallucinated source IDs
    cause the differential to be dropped, and penalize Evidence Density.
    """

    @classmethod
    def verify_and_filter(
        cls,
        analysis: CaseAnalysis,
        retrieved_source_ids: Set[str],
        symptoms: List[Dict[str, str]],
        vitals: Dict[str, str],
    ) -> Tuple[CaseAnalysis, List[DifferentialItem], float]:
        """
        Filters differentials against valid RAG source IDs.
        Returns:
            - filtered_analysis: CaseAnalysis with ungrounded differentials stripped
            - dropped_differentials: list of discarded items
            - evidence_density_score: calculated density [0.0 - 1.0] reflecting grounded citations
        """
        valid_differentials: List[DifferentialItem] = []
        dropped_differentials: List[DifferentialItem] = []

        total_diffs = len(analysis.differentials)

        for diff in analysis.differentials:
            # If retrieved sources were provided, differential must cite at least one valid source ID
            # and ALL cited source IDs must exist in the retrieved set
            if retrieved_source_ids:
                if not diff.source_ids:
                    # Missing grounding citation
                    dropped_differentials.append(diff)
                    continue
                
                cited_set = set(diff.source_ids)
                if not cited_set.issubset(retrieved_source_ids):
                    # Cited hallucinated or unretrieved source IDs
                    dropped_differentials.append(diff)
                    continue

            valid_differentials.append(diff)

        # Compute grounded Evidence Density:
        # Base count of grounded specific clinical findings cited across valid differentials
        grounded_findings_count = 0
        total_expected_findings = max(1, len(symptoms) + (1 if vitals else 0))

        # Check citations of real patient findings in supporting evidence
        all_patient_terms: Set[str] = set()
        for s in symptoms:
            if isinstance(s, dict):
                sname = (s.get("symptom") or "").lower()
                if sname:
                    all_patient_terms.add(sname)

        for diff in valid_differentials:
            for ev in diff.supporting_evidence:
                ev_lower = ev.lower()
                for term in all_patient_terms:
                    if term in ev_lower:
                        grounded_findings_count += 1
                        break

        # Evidence density ratio
        raw_density = min(1.0, 0.4 + (grounded_findings_count / total_expected_findings) * 0.6)

        # Apply deterministic penalty if any differentials were dropped due to ungrounded sources
        if total_diffs > 0 and dropped_differentials:
            penalty = 0.25 * (len(dropped_differentials) / total_diffs)
            evidence_density_score = max(0.0, round(raw_density - penalty, 2))
        else:
            evidence_density_score = round(raw_density, 2)

        # Construct updated CaseAnalysis with valid differentials
        filtered_analysis = analysis.model_copy(
            update={"differentials": valid_differentials}
        )

        return filtered_analysis, dropped_differentials, evidence_density_score
