from __future__ import annotations

from typing import List, Literal
from pydantic import BaseModel, Field

UrgencyLiteral = Literal["emergency", "urgent", "routine", "self_care"]
LikelihoodLiteral = Literal["more_likely", "possible", "less_likely"]
GeriatricConcernLiteral = Literal[
    "delirium",
    "fall_risk",
    "polypharmacy",
    "frailty",
    "atypical_presentation",
    "sepsis_pattern",
    "none",
]


class DifferentialItem(BaseModel):
    """
    Ordinal differential diagnosis generated by LLM.
    Strictly prohibits numeric probabilities to eliminate false precision.
    """
    condition: str = Field(..., description="Suspected clinical diagnosis or syndrome")
    likelihood: LikelihoodLiteral = Field(
        ...,
        description="Ordinal clinical likelihood (more_likely, possible, less_likely)",
    )
    supporting_evidence: List[str] = Field(
        default_factory=list,
        max_length=6,
        description="Clinical evidence supporting this condition (max 6 items)",
    )
    against_or_missing: List[str] = Field(
        default_factory=list,
        max_length=6,
        description="Findings against or critical data missing (max 6 items)",
    )
    source_ids: List[str] = Field(
        default_factory=list,
        description="RAG chunk source IDs grounding this diagnosis",
    )


class CaseAnalysis(BaseModel):
    """
    Primary output schema for AI clinical summarization and explanation.
    LLM acts purely as an explainer and cannot set triage level.
    """
    summary: str = Field(
        ...,
        max_length=1200,
        description="Concise clinical summary (max 1200 characters)",
    )
    suggested_urgency: UrgencyLiteral = Field(
        ...,
        description="Independent AI suggestion for agreement comparison only",
    )
    urgency_rationale: str = Field(
        ...,
        description="Clinical reasoning explaining the urgency suggestion",
    )
    differentials: List[DifferentialItem] = Field(
        default_factory=list,
        max_length=5,
        description="Ranked differential diagnoses (up to 5)",
    )
    followup_questions: List[str] = Field(
        default_factory=list,
        max_length=6,
        description="Targeted follow-up questions to resolve clinical ambiguity (max 6)",
    )
    geriatric_concerns: List[GeriatricConcernLiteral] = Field(
        default_factory=list,
        description="Identified geriatric clinical risk domains",
    )
    is_rule_based_fallback: bool = Field(
        default=False,
        description="Indicates whether this analysis was generated by the deterministic fallback engine",
    )
